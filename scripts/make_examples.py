"""Write the three demo examples (one per scenario) with audio, plots and metrics.

    python scripts/make_examples.py --config results/ablations/tuned.yaml [--out examples]

To avoid cherry-picking, the first eval sample of each scenario (``*_000``) is
used unless --ids is given. Requires cached eval estimates.
"""

from __future__ import annotations

import json
from pathlib import Path

from _common import base_parser, config_from_args
from evaluate import md_table

import pandas as pd

from sonic.audio import SR, save_audio
from sonic.dataset import SCENARIOS
from sonic.evaluation import evaluate_sample
from sonic.experiment import apply_method, load_cached
from sonic.pipeline import METHODS
from sonic.plotting import plot_localization

SHOW = ["sdr_bg", "sisdr_bg", "sdr_bg_out", "sdr_bg_in", "target_suppression_db", "loc_iou", "loc_f1"]


def main():
    p = base_parser(__doc__)
    p.add_argument("--split", default="eval")
    p.add_argument("--ids", nargs="+", default=[f"{s}_000" for s in SCENARIOS])
    p.add_argument("--out", default="examples")
    args = p.parse_args()
    cfg = config_from_args(args)
    root = Path(args.out)
    rows = []
    for k, sid in enumerate(args.ids, start=1):
        cs = load_cached(cfg, args.split, sid)
        smp = cs.sample
        d = root / f"example{k}_{smp.meta['scenario']}"
        save_audio(d / "mixture.wav", smp.x, SR)
        save_audio(d / "reference.wav", smp.b, SR)
        (d / "instruction.txt").write_text(smp.meta["instruction"] + "\n")
        metrics = {}
        for method in METHODS:
            out = apply_method(cs, method, cfg)
            save_audio(d / f"{method}.wav", out.y, SR)
            metrics[method] = evaluate_sample(smp.x, out.y, smp.s, smp.b, smp.intervals, SR,
                                              pred_intervals=out.intervals,
                                              mask=out.mask if method != "baseline" else None)
            metrics[method]["intervals"] = out.intervals
            if method == "sonic":
                loc = out.localization
                plot_localization(smp.x, SR, loc.frame_times, loc.frame_scores, loc.threshold, out.intervals,
                                  smp.intervals, out.mask, f'"{smp.meta["instruction"]}"', d / "localization.png")
            rows.append({"example": k, "sample_id": sid, "method": method,
                         **{m: metrics[method].get(m, float("nan")) for m in SHOW}})
        meta = {"sample_id": sid, "instruction": smp.meta["instruction"], "target_prompt": smp.meta["target_prompt"],
                "ground_truth_intervals": smp.intervals, "metrics": metrics, "source_files": smp.meta["sources"]}
        (d / "metrics.json").write_text(json.dumps(meta, indent=2, default=float))
        print(f"wrote {d}")
    table = pd.DataFrame(rows)
    instr = {k: load_cached(cfg, args.split, sid).sample.meta["instruction"] for k, sid in enumerate(args.ids, 1)}
    md = ["# SONIC demo examples", "",
          "Generated by `scripts/make_examples.py` from the eval split (first sample of each scenario, not hand-picked).",
          "Audio sources: ESC-50 (CC BY-NC 3.0) and LibriSpeech (CC BY 4.0).", ""]
    md += [f"- Example {k}: \"{t}\"" for k, t in instr.items()]
    md += ["", md_table(table)]
    (root / "README.md").write_text("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
